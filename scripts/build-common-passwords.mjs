// Regenerates src/lib/users/common-passwords.ts from the NCSC "100k most used
// passwords" list. Usage: node scripts/build-common-passwords.mjs [local.txt]
// With no argument it downloads the list from SecLists.
import { readFileSync, writeFileSync } from "fs";

const SOURCE =
  "https://raw.githubusercontent.com/danielmiessler/SecLists/master/Passwords/Common-Credentials/100k-most-used-passwords-NCSC.txt";
// Keep in step with PASSWORD_MIN_LENGTH in src/lib/users/password-policy.ts.
const MIN_LENGTH = 10;

const text = process.argv[2]
  ? readFileSync(process.argv[2], "utf8")
  : await (await fetch(SOURCE)).text();
const all = text.split(/\r?\n/).map((s) => s.trim()).filter(Boolean);

const long = [];
const seenLong = new Set();
const base = [];
const seenBase = new Set();
for (const p of all) {
  const lower = p.toLowerCase();
  if (lower.length >= MIN_LENGTH && /^[\x21-\x7e]+$/.test(lower) && !seenLong.has(lower)) {
    seenLong.add(lower);
    long.push(lower);
  }
  if (base.length < 1000 && /^[a-z]{4,}$/.test(lower) && !seenBase.has(lower)) {
    seenBase.add(lower);
    base.push(lower);
  }
}

const out = `// GENERATED by scripts/build-common-passwords.mjs from the NCSC "100k most used
// passwords" list (via SecLists, MIT). Regenerate rather than edit by hand.
//
// LONG: every entry at least PASSWORD_MIN_LENGTH long, lowercased. Shorter ones
// are already refused by the length rule, which keeps this file small enough
// to load in the browser for the strength meter.
// BASE_WORDS: the 1,000 most common all-letter passwords, so a common word with
// digits or symbols tacked on ("password2024!") is caught too.
export const LONG = ${JSON.stringify(long.join("\n"))};
export const BASE_WORDS = ${JSON.stringify(base.join("\n"))};
`;
writeFileSync(new URL("../src/lib/users/common-passwords.ts", import.meta.url), out);
console.log(`${long.length} long entries, ${base.length} base words`);
