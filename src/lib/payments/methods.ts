import type { PaymentMethod } from "@/lib/types";

// Stage 3 payment methods — the client-safe registry (no provider code, no secrets).
//
// NOTHING HERE IS A LIVE INTEGRATION. There are no provider credentials and no processor for any method. Each method
// below states what would be needed to activate it; until that exists, the method can be switched on in the
// Executive Office but is never offered to customers (lib/payments/config.ts), except Zelle and bank transfer, which
// are verified by a person and need only their receiving details configured.
//
// Inventory policy:
//   reserve          — stock is held at checkout for the method's reservation window and committed on payment
//   on_confirmation  — nothing is held at checkout; stock is deducted when payment is confirmed (and if it has run
//                      out by then, the order goes to Administrative Review instead of overselling)

export type PaymentFamily = "crypto" | "manual" | "ach" | "card";
export type InventoryPolicy = "reserve" | "on_confirmation";

export type PaymentMethodInfo = {
  id: PaymentMethod;
  label: string;
  family: PaymentFamily;
  /** Who verifies the payment: a provider notification, or a person (who must record the reference). */
  verification: "provider" | "human";
  /** Default policy; reservation length is set in the Executive Office for the methods that allow it. */
  inventoryPolicy: InventoryPolicy;
  reservationConfigurable: boolean;
  /** Owner-set default (spec: crypto 30 minutes). null = no reservation. */
  defaultReservationMinutes: number | null;
  /** True only when a real, approved provider integration is wired in. None is. */
  liveIntegration: false;
  /** Plain statement of what activation requires. Unknowns are stated as unknown. */
  activationRequires: string;
  /** Kept for existing orders only; not one of the eight Stage 3 methods. */
  legacy?: boolean;
};

